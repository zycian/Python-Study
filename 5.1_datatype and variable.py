#布尔值//布尔值就是-判断题的答案-只有两个值：True和 False

#在Python中，可以直接用True、False表示布尔值（请注意大小写）
#也可以通过布尔运算计算出来
print(3>1)
print('a'in'fuck')
#布尔值可以用and、or和not运算   //逻辑运算符
#and运算是与运算，只有所有都为True，and运算结果才是True     //即&&
#or运算是或运算，只要其中有一个为True，or运算结果就是True   //即||
#not运算是非运算，它是一个单目运算符，把True变成False，False变成True    //即！
#用于条件判断，如
age = input('age')
print(age)
if age >= '18': #注意要加‘’
    print('adult')
else:
    print('teenager')


