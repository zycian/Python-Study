#变量

#变量不仅可以是数字，还可以是任意数据类型
#变量名必须是大小写英文、数字和_的组合，且不能用数字开头
a = 1           #整数
t_007 = 'T007'  #字符串
Answer = True   #布尔值
#等号=是赋值语句，可以把任意数据类型赋值给变量
#同一个变量可以反复赋值，而且可以是不同类型的变量

#这种变量本身类型不固定的语言称之为--动态语言，与之对应的是--静态语言//原来如此
#和静态语言相比，动态语言更灵活
#最后，理解变量在计算机内存中的表示也非常重要。当我们写：
#   a = 'ABC'
#Python解释器干了两件事情：
#   1.在内存中创建了一个'ABC'的字符串；
#   2.在内存中创建了一个名为a的变量，并把它指向'ABC'
#也可以把一个变量a赋值给另一个变量b，这个操作实际上是把变量b指向变量a所指向的数据
#       //也就是说给的值不变，变量是一个名字标签类似指针，读取变量是在读取它所指向的给的值


#常量

#在Python中，通常用全部大写的变量名表示常量如
PI = 3.14159265359
#但事实上PI仍然是一个变量，Python根本没有任何机制保证PI不会被改变
#所以，用全部大写的变量名表示常量只是习惯上的用法，如果你一定要改变变量PI的值，也没人能拦住你



#最后解释一下整数的除法为什么也是精确的。在Python中，有两种除法
#一种除法是/    10/3    得3.33333333333......
#一种除法是//，称为地板除，两个整数的除法仍然是整数 10/3    得3
#还有余数   10%3    得1 

#Python的整数没有大小限制；浮点数也没有大小限制，但是超出一定范围就直接表示为inf（无限大）