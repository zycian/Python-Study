# 抽象

# 抽象是数学中非常常见的概念。举个例子：
# 计算数列的和，比如：1 + 2 + 3 + ... + 100，写起来十分不方便
# 于是数学家发明了求和符号∑
# 这种抽象记法非常强大，因为我们看到 ∑ 就可以理解成求和，而不是还原成低级的加法运算
# 而且，这种抽象记法是可扩展的
# 可见，借助抽象，我们才能不关心底层的具体计算过程，而直接在更高的层次上思考问题。
# 写计算机程序也是一样，函数就是最基本的一种代码抽象的方式。